"""Generate ContextData.tla (MeasuredHas) from matrix.json. Thresholds: >=0.95 always, <=0.05 never, else sometimes.

Seed and seed+retry rows are pooled as "seed", follow-up and follow-up+retry as "followup", weighted by call count.
Items with no structured equivalent in the engine (gov_block, sender_id_verified) are "never" in measured mode:
the sender id reaches prompts only as text inside the rendered observation line, next to the display name.
"""
import collections
import json
import sys

M = json.load(open(sys.argv[1]))
OUT = sys.argv[2]
STAGE = {"ActionSelectionPDMAEvaluator": "aspdma", "TSASPDMA": "tsaspdma", "coherence_conscience": "coherence",
         "entropy_conscience": "entropy", "epistemic_humility_conscience": "epistemic",
         "optimization_veto_conscience": "optveto"}
SCEN = {"S1 default (no rule)": "S1", "S2 rule stated by user (same message)": "S2",
        "S3 rule stated by WA (earlier message, same channel)": "S3", "S4 guidance task after WA answer": "S4",
        "S5 after amendment landed (other user)": "S5", "S6 impersonator after genuine correction": "S6"}
ITEM = {"user_msg": "user_msg", "history": "history", "display_name": "display_name",
        "raw_ctx_via_record": "raw_ctx_via_record", "identity": "identity", "rule_visible": "rule_any",
        "rule_in_identity": "rule_in_identity", "wa_guidance": "wa_guidance"}

acc = collections.defaultdict(lambda: [0, collections.Counter()])
for r in M["rows"]:
    st, sc = STAGE.get(r["handler"]), SCEN.get(r["scenario"])
    if not st or not sc:
        continue
    k = "seed" if r["thought"].startswith("seed") else "followup"
    a = acc[(st, sc, k)]
    a[0] += r["n"]
    for it, src in ITEM.items():
        a[1][it] += r.get(src, 0) * r["n"]


def level(f):
    return "always" if f >= 0.95 else ("never" if f <= 0.05 else "sometimes")


lines, report = [], []
for (st, sc, k), (n, c) in sorted(acc.items()):
    for it in ITEM:
        f = c[it] / n
        lines.append(f'    [] <<"{st}", "{sc}", "{k}", "{it}">> = key -> "{level(f)}"')
        report.append((st, sc, k, it, round(f, 2), n))

body = "\n".join(lines).replace("    [] ", "    CASE ", 1)
tla = f"""---------------------------- MODULE ContextData ----------------------------
(* GENERATED by ctxmap/gen_contextdata.py from ctxmap/matrix.json -- do not edit.            *)
(* Measured presence of each context item in each stage's prompt, per scenario and thought.  *)
(* >= 0.95 of calls: "always"; <= 0.05: "never"; otherwise "sometimes".                     *)
(* No data for a combination (the stage never ran there): "never".                           *)
(* gov_block and sender_id_verified do not exist in the engine: "never".                     *)

MeasuredHas(stage, s, k, item) ==
  LET key == <<stage, s, k, item>> IN
  IF item \\in {{"gov_block", "sender_id_verified"}} THEN "never"
  ELSE
{body}
    [] OTHER -> "never"
=============================================================================
"""
open(OUT, "w").write(tla)
json.dump(report, open(OUT.replace(".tla", "_report.json"), "w"))
print(len(lines), "entries ->", OUT)
